import sqlite3
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path

DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
IS_POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))
_USER_REGISTRATION_LOCK_ID = 4850182352543743302


class UserLimitReached(Exception):
    """Raised when account creation would exceed the configured registration cap."""


if os.getenv("CYBER_SENTINEL_DB"):
    DATABASE = Path(os.environ["CYBER_SENTINEL_DB"])
elif os.getenv("VERCEL") == "1":
    # Without DATABASE_URL, Vercel can only use /tmp, which is wiped between cold starts
    # and not shared between instances. Set DATABASE_URL (free Neon Postgres) instead.
    DATABASE = Path("/tmp/cyber-sentinel/security.db")
else:
    DATABASE = Path(__file__).with_name("security.db")

if IS_POSTGRES:
    import psycopg  # Only needed for PostgreSQL deployments.

    INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)
else:
    INTEGRITY_ERRORS = (sqlite3.IntegrityError,)


class _Row:
    """Row that supports row[0], row["name"] and dict(row), like sqlite3.Row."""

    __slots__ = ("_names", "_values")

    def __init__(self, names, values):
        self._names = names
        self._values = values

    def __getitem__(self, key):
        return self._values[key] if isinstance(key, int) else self._values[self._names.index(key)]

    def keys(self):
        return list(self._names)


def _pg_row_factory(cursor):
    names = [column.name for column in cursor.description or ()]
    return lambda values: _Row(names, values)


class _PostgresConnection:
    """Gives a psycopg connection the small sqlite3-style API this module uses."""

    def __init__(self, url):
        # prepare_threshold=None keeps it compatible with pooled (PgBouncer) connection strings.
        self._connection = psycopg.connect(url, connect_timeout=10, prepare_threshold=None)

    @staticmethod
    def _sql(sql):
        return sql.replace("?", "%s")

    def execute(self, sql, params=()):
        cursor = self._connection.cursor(row_factory=_pg_row_factory)
        cursor.execute(self._sql(sql), params)
        return cursor

    def executemany(self, sql, rows):
        cursor = self._connection.cursor()
        cursor.executemany(self._sql(sql), rows)
        return cursor

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()

    def close(self):
        self._connection.close()


def _connect():
    if IS_POSTGRES:
        return _PostgresConnection(DATABASE_URL)
    DATABASE.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(str(DATABASE), timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys=ON")
    connection.execute("PRAGMA busy_timeout=10000")
    return connection


@contextmanager
def get_connection():
    connection = _connect()
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def _insert(connection, sql, params):
    """Run an INSERT and return the new row id (works on SQLite 3.35+ and PostgreSQL)."""
    return connection.execute(f"{sql} RETURNING id", params).fetchall()[0][0]


